import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/**
 * Writes the two sources a theme is checked against:
 *
 * - `src/generated/contract.ts` — the token contract and the name unions
 *   `defineTheme` is typed with. `ComponentToken` is every custom property a
 *   family stylesheet reads that the contract does not declare, taken from the
 *   `<family>.tokens.json` files `packages/styles/src/tokens.test.mjs` holds
 *   equal to the stylesheets.
 * - `src/generated/hooks.json` — the public selectors a theme rule may use:
 *   every `data-ui` value with the parts its family contract declares for it
 *   (members' parts, `rootPart`, and the parts another contract renders as
 *   that family's root in `partIdentity.parts`), and every `data-*` attribute the
 *   family contracts declare or the family stylesheets select, spelled as it
 *   is in the DOM and kept only when a binding or `@slotted/core` writes it
 *   (`writtenAttributes`).
 *
 * `--check` writes nothing and exits 1 when either file is stale.
 */
const PACKAGE = fileURLToPath(new URL('../', import.meta.url));
const REPOSITORY = join(PACKAGE, '../..');
const STYLES = join(REPOSITORY, 'packages/styles/src');
const SPECS = join(REPOSITORY, 'specs/components');
const HEADER = '// Generated by packages/theme/scripts/generate-sources.mjs. Do not edit.\n';

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));
const families = () =>
  readdirSync(STYLES, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

export function componentTokens(contract) {
  const declared = new Set(contract.tokens.map((token) => token.name));
  const names = new Set();
  for (const family of families()) {
    const file = readdirSync(join(STYLES, family)).find((name) => name.endsWith('.tokens.json'));
    if (!file) continue;
    for (const name of readJson(join(STYLES, family, file)))
      if (!declared.has(name)) names.add(name);
  }
  return [...names].sort();
}

const union = (names) =>
  names.length === 0 ? '  never' : names.map((name) => `  | '${name}'`).join('\n');

export function contractSource() {
  const contract = readJson(join(PACKAGE, 'src/contract.json'));
  // `groups` documents the tokens for the published page; no theme reads it at run time.
  delete contract.groups;
  const names = (predicate) => contract.tokens.filter(predicate).map((token) => token.name);
  const component = componentTokens(contract);
  return (
    HEADER +
    "import type { TokenContract } from '../contract-types';\n\n" +
    `export const contract: TokenContract = ${JSON.stringify(contract, null, 2)};\n\n` +
    `export type BaseToken =\n${union(names((token) => token.axis === 'base'))};\n\n` +
    `export type SchemeToken =\n${union(names((token) => token.axis === 'scheme'))};\n\n` +
    `export type DensityToken =\n${union(names((token) => token.axis === 'density'))};\n\n` +
    `export type MotionToken =\n${union(names((token) => token.reducedMotion))};\n\n` +
    `export type ColorToken =\n${union(names((token) => token.axis === 'scheme' && token.type === 'color'))};\n\n` +
    `export type ComponentToken =\n${union(component)};\n\n` +
    `export const COMPONENT_TOKENS: readonly ComponentToken[] = ${JSON.stringify(component, null, 2)};\n`
  );
}

/** The directories whose modules write a family's attributes to the DOM. */
const BINDINGS = ['packages/react/src', 'packages/angular', 'packages/core/src'];
/** Tests, stories and documentation name attributes without writing them. */
const NOT_SHIPPED = /\.(test|spec|stories|docs)\.[cm]?[jt]sx?$|\.d\.ts$/;
const kebab = (name) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

function* sourceFiles(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name === 'dist') continue;
    const path = join(directory, entry.name);
    if (entry.isDirectory()) yield* sourceFiles(path);
    else if (/\.(ts|tsx|html)$/.test(entry.name) && !NOT_SHIPPED.test(entry.name)) yield path;
  }
}

/**
 * Every `data-*` attribute the React and Angular bindings and `@slotted/core`
 * name in shipped source — a JSX prop, an Angular `[attr.data-*]` binding or
 * template attribute, a `setAttribute` argument, or a `dataset` property in
 * its DOM spelling. A contract option that no module names is never written
 * to the DOM.
 */
export function writtenAttributes() {
  const written = new Set();
  for (const root of BINDINGS) {
    for (const file of sourceFiles(join(REPOSITORY, root))) {
      const source = readFileSync(file, 'utf8');
      for (const [name] of source.matchAll(/(?<![\w-])data-[a-z][a-z0-9-]*[a-z0-9]/g))
        written.add(name);
      for (const [, property, key] of source.matchAll(
        /\.dataset(?:\.([A-Za-z]\w*)|\[['"]([A-Za-z]\w*)['"]\])/g,
      ))
        written.add(`data-${kebab(property ?? key)}`);
    }
  }
  return written;
}

export function hooksSource() {
  const ui = new Map();
  const attributes = new Set();
  const addParts = (name, parts) => ui.set(name, new Set([...(ui.get(name) ?? []), ...parts]));

  for (const directory of readdirSync(SPECS).sort()) {
    const file = join(SPECS, directory, 'contract.json');
    if (!existsSync(file)) continue;
    const contract = readJson(file);
    addParts(
      contract.ui,
      Object.values(contract.members ?? {}).flatMap((member) => member.parts ?? []),
    );
    // A member whose root is written under another part name: message's bubble is
    // `data-ui="message" data-part="bubble"`.
    addParts(contract.ui, Object.values(contract.rootPart ?? {}));
    // A part rendered as another family's root: split-button's primary is
    // `data-ui="button" data-part="primary"`.
    for (const [part, ui] of Object.entries(contract.partIdentity?.parts ?? {}))
      addParts(ui, [part]);
    for (const axis of Object.keys(contract.axes ?? {})) attributes.add(`data-${kebab(axis)}`);
    for (const attribute of Object.values(contract.stateAttributes ?? {}))
      attributes.add(attribute);
    // `dataAttributes` is keyed either by attribute (with its meaning as the value) or by
    // part (with the attributes that part carries as the value).
    for (const [key, value] of Object.entries(contract.dataAttributes ?? {})) {
      if (key.startsWith('data-')) attributes.add(key);
      else for (const attribute of value) attributes.add(attribute);
    }
  }
  for (const family of families()) {
    for (const file of readdirSync(join(STYLES, family)).filter((name) => name.endsWith('.css'))) {
      const css = readFileSync(join(STYLES, family, file), 'utf8');
      // A `data-ui` a stylesheet selects without a contract (spinner) is a family with no parts.
      for (const [, name] of css.matchAll(/\[data-ui=['"]([\w-]+)['"]\]/g)) addParts(name, []);
      for (const [, name] of css.matchAll(/\[data-ui-([\w-]+)\]/g)) addParts(name, []);
      /* `data-part-<part>` and `data-ui-<family>` are the selector keys the
         stylesheet matches; a theme rule names the public `data-part` and
         `data-ui`, so the keys are not hooks. */
      for (const [, attribute] of css.matchAll(/\[(data-[a-z0-9-]+)/g)) {
        if (!attribute.startsWith('data-part-') && !attribute.startsWith('data-ui-')) {
          attributes.add(attribute);
        }
      }
    }
  }
  const sorted = Object.fromEntries(
    [...ui.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([name, parts]) => [name, [...parts].sort()]),
  );
  const written = writtenAttributes();
  const reflected = [...attributes].filter((attribute) => written.has(attribute)).sort();
  return `${JSON.stringify({ ui: sorted, attributes: reflected }, null, 2)}\n`;
}

export const OUTPUTS = {
  'src/generated/contract.ts': contractSource,
  'src/generated/hooks.json': hooksSource,
};

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes('--check');
  let stale = false;
  mkdirSync(join(PACKAGE, 'src/generated'), { recursive: true });
  for (const [path, source] of Object.entries(OUTPUTS)) {
    const target = join(PACKAGE, path);
    const after = source();
    const before = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (after === before) continue;
    if (check) {
      console.error(`${path} is stale; run: pnpm --filter @slotted/theme generate`);
      stale = true;
    } else writeFileSync(target, after);
  }
  if (stale) process.exit(1);
}
