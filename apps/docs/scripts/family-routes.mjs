/**
 * One route file per documented family, `src/pages/[framework]/components/<family>.astro`.
 *
 * The build hands a page the stylesheets of every module its route reaches,
 * dynamic imports included. One route for every family reached every example,
 * so every page carried every family's CSS: 50 sheets, 5,851 rules, 1.6 MB,
 * and a full style recalculation six times slower than the site's own CSS
 * alone. A route per family globs that family's examples and nothing else.
 *
 * `node scripts/family-routes.mjs` writes the routes; `--check` fails when one
 * is missing, stale or left over, and writes nothing.
 */
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';

const content = new URL('../src/content/components/', import.meta.url);
const routes = new URL('../src/pages/[framework]/components/', import.meta.url);
const MARK = '/* Generated by scripts/family-routes.mjs';

const route = (family) => `---
${MARK}: one route per family, so the build hands
   this page only this family's stylesheets. */
import { getEntry } from 'astro:content';
import type { ComponentType } from 'react';

import FamilyPage from '../../../components/FamilyPage.astro';
import type { AngularExampleModule } from '../../../runtime/angular-component';
import { FRAMEWORKS, type Framework } from '../../../runtime/frameworks';

export function getStaticPaths() {
  return FRAMEWORKS.map((framework) => ({ params: { framework } }));
}

const entry = await getEntry('components', '${family}');
if (!entry) throw new Error('No components entry "${family}"');
const examples = {
  react: import.meta.glob<{ default: ComponentType }>('../../../../examples/react/${family}/*.tsx'),
  angular: import.meta.glob<AngularExampleModule>('../../../../examples/angular/${family}/*.ts'),
};
---

<FamilyPage entry={entry} framework={Astro.params.framework as Framework} examples={examples} />

<script>
  import { startPreviews } from '../../../runtime/client';

  startPreviews({
    react: import.meta.glob('../../../../examples/react/${family}/*.tsx'),
    angular: import.meta.glob('../../../../examples/angular/${family}/*.ts'),
  });
</script>
`;

const families = readdirSync(content)
  .filter((file) => file.endsWith('.mdx'))
  .map((file) => file.slice(0, -'.mdx'.length))
  .sort();
const check = process.argv.includes('--check');
const problems = [];

for (const family of families) {
  const file = new URL(`${family}.astro`, routes);
  const expected = route(family);
  if (existsSync(file) && readFileSync(file, 'utf8') === expected) continue;
  if (check) problems.push(`${family}.astro is ${existsSync(file) ? 'stale' : 'missing'}`);
  else writeFileSync(file, expected);
}

for (const file of readdirSync(routes).filter((name) => name.endsWith('.astro'))) {
  const family = file.slice(0, -'.astro'.length);
  if (families.includes(family)) continue;
  if (!readFileSync(new URL(file, routes), 'utf8').includes(MARK)) continue;
  if (check) problems.push(`${file} has no family page`);
  else rmSync(new URL(file, routes));
}

if (problems.length > 0) {
  console.error(`${problems.join('\n')}\nRun: node scripts/family-routes.mjs`);
  process.exit(1);
}
